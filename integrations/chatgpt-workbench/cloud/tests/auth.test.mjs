import test from 'node:test';
import assert from 'node:assert/strict';
import {generateKeyPair,SignJWT,createLocalJWKSet,exportJWK} from 'jose';
import {authorize,requireScope,authConfig} from '../auth.mjs';
import worker from '../worker.mjs';
test('OAuth: 签名、作者身份、issuer、audience、过期与 scope；缺配置时拒绝访问',async()=>{
  const {privateKey,publicKey}=await generateKeyPair('RS256');
  const keyset=createLocalJWKSet({keys:[{...await exportJWK(publicKey),kid:'test',alg:'RS256'}]});
  const env={AUTH0_ISSUER:'https://tenant.auth0.com/',MCP_RESOURCE:'https://novel.example/mcp',OWNER_SUB:'auth0|author'};
  const token=async({sub=env.OWNER_SUB,issuer=env.AUTH0_ISSUER,audience=env.MCP_RESOURCE,exp='5m',scope='novel:read novel:write'}={})=>new SignJWT({scope}).setProtectedHeader({alg:'RS256',kid:'test'}).setSubject(sub).setIssuer(issuer).setAudience(audience).setIssuedAt().setExpirationTime(exp).sign(privateKey);
  const req=t=>new Request(env.MCP_RESOURCE,{headers:{Authorization:`Bearer ${t}`}});
  const auth=await authorize(req(await token()),env,keyset);requireScope(auth,'novel:write');
  await assert.rejects(authorize(req(await token({sub:'auth0|someone-else'})),env,keyset),{status:403});
  for(const input of [{issuer:'https://other.auth0.com/'},{audience:'https://other.example/mcp'},{exp:'-1m'}])await assert.rejects(authorize(req(await token(input)),env,keyset),{status:401});
  assert.throws(()=>requireScope({...auth,scopes:new Set(['novel:read'])},'novel:write'),{status:403});
  await assert.rejects(authorize(req('forged'),env,keyset),{status:401});
  assert.throws(()=>authConfig({}),{status:503});
  const absent=await worker.fetch(new Request(env.MCP_RESOURCE),env);assert.equal(absent.status,401);
  assert.match(absent.headers.get('WWW-Authenticate'),/oauth-protected-resource\/mcp/);
  const metadata=await worker.fetch(new Request('https://novel.example/.well-known/oauth-protected-resource/mcp'),env);
  assert.equal((await metadata.json()).resource,env.MCP_RESOURCE);
  const unpinned={AUTH0_ISSUER:env.AUTH0_ISSUER,MCP_RESOURCE:env.MCP_RESOURCE};
  const discovery=await worker.fetch(new Request('https://novel.example/.well-known/oauth-protected-resource/mcp'),unpinned);
  assert.equal(discovery.status,200);
  assert.equal((await worker.fetch(new Request(env.MCP_RESOURCE),unpinned)).status,401);
  await assert.rejects(authorize(req(await token()),unpinned,keyset),{status:503});
  const browserHeaders={Origin:'https://chatgpt.com','Access-Control-Request-Method':'POST','Access-Control-Request-Headers':'authorization,content-type,mcp-protocol-version'};
  const preflight=await worker.fetch(new Request(env.MCP_RESOURCE,{method:'OPTIONS',headers:browserHeaders}),unpinned);
  assert.equal(preflight.status,204);
  assert.equal(preflight.headers.get('Access-Control-Allow-Origin'),'https://chatgpt.com');
  assert.match(preflight.headers.get('Access-Control-Allow-Headers'),/Authorization/);
  const browserChallenge=await worker.fetch(new Request(env.MCP_RESOURCE,{headers:browserHeaders}),unpinned);
  assert.equal(browserChallenge.status,401);
  assert.equal(browserChallenge.headers.get('Access-Control-Allow-Origin'),'https://chatgpt.com');
  assert.match(browserChallenge.headers.get('Access-Control-Expose-Headers'),/WWW-Authenticate/);
  const hostile=await worker.fetch(new Request(env.MCP_RESOURCE,{method:'OPTIONS',headers:{Origin:'https://evil.example'}}),unpinned);
  assert.equal(hostile.status,403);
  assert.equal(hostile.headers.get('Access-Control-Allow-Origin'),null);
  assert.equal((await worker.fetch(new Request('https://novel.example/index.html'),env)).status,404);
});
